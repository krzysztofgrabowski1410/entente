"""Shared hypothesis strategies: reachable positions and order-sheet samplers.

Positions are generated by playing k random phases from the map's start, so
every one of them is reachable in play rather than merely well-formed. Order
sheets are then sampled over that position by one of three samplers:

* the general, mostly-legal sampler -- Phase 0 is part of the system under
  test, so occasionally-invalid orders are wanted, not avoided;
* a convoy-rich sampler that concentrates probability on convoy attempts with
  real potential chains, fleets convoying or attacking convoying seas, and the
  supports that decide a chain's viability (docs/adjudication.tex Sec. 3.5 and
  Sec. 5.2);
* a Beleriand sampler that stacks Areas and rolls the variant orders --
  Dislodge, Bar, strength-prefixed specs -- so the differential walks the
  stacking machinery the standard map never reaches
  (docs/adjudication.tex Sec. 3.4, Sec. 4.2, Sec. 4.3).

A fourth sampler leaves the shipped maps. The Beleriand sampler above rolls no
convoy at all, and no shipped coast touches both a marked and a free sea, so the
convoy toll's interesting inputs -- which seas a convoy was ordered through --
never vary there. The two-beach sampler draws boards and sheets directly on the
synthetic map that has such a coast (:mod:`tests.engine.two_beach`;
docs/adjudication.tex Sec. 2).
"""

from __future__ import annotations

from dataclasses import replace

from hypothesis import strategies as st

from entente.engine.adjudicator import adjudicate
from entente.engine.adjudicator.common import potential_chain
from entente.engine.map import Location, MapGraph, Terrain, UnitKind, load_map
from entente.engine.orders import (
    Bar,
    Convoy,
    Dislodge,
    Hold,
    Move,
    Order,
    Support,
    UnitRef,
    parse_unit_spec,
)
from entente.engine.rules import RULESETS, STANDARD
from entente.engine.state import State, Unit
from entente.variants.beleriand import BELERIAND
from tests.engine.two_beach import TWO_BEACH

GRAPH = load_map("standard")
BELERIAND_GRAPH = load_map("beleriand")

assert RULESETS["beleriand"] is BELERIAND  # registration is part of the system under test

COASTAL_PROVINCES = sorted(
    key for key, p in GRAPH.provinces.items() if p.terrain is Terrain.COASTAL
)

_MAX_CONVOY_ATTEMPTS = 6
"""Cap on via-convoy moves per sheet: keeps the enumerator's per-SCC
enumeration comfortably inside its bound on adversarial tangles."""


def start_state() -> State:
    """Build the standard map's opening position."""
    units = [
        Unit(power, *_parse_spec(spec))
        for power, specs in GRAPH.starting_units.items()
        for spec in specs
    ]
    return State.of("standard", "S1901M", units)


def _parse_spec(spec: str) -> tuple[UnitKind, Location]:
    kind_text, _, location_text = spec.partition(" ")
    province, _, coast = location_text.partition("/")
    return UnitKind(kind_text), Location(province, coast or None)


def _destinations(graph: MapGraph, unit: Unit) -> list[Location]:
    if unit.kind is UnitKind.ARMY:
        return [Location(p) for p in sorted(graph.army_adjacency[unit.location.province])]
    return sorted(
        graph.fleet_adjacency[unit.location], key=lambda loc: (loc.province, loc.coast or "")
    )


def _can_support_into(graph: MapGraph, unit: Unit, province: str) -> bool:
    if unit.kind is UnitKind.ARMY:
        return graph.terrain(province) is not Terrain.SEA and graph.army_reachable(
            unit.location.province, province
        )
    return bool(graph.fleet_destinations(unit.location, province))


@st.composite
def sheets_for(draw: st.DrawFn, state: State) -> dict[str, list[Order]]:
    """Sample a mostly-legal sheet for every unit on the board.

    Some rolls produce orders Phase 0 will reject, and that is the point:
    Phase 0 is part of what the properties test.
    """
    primitive: dict[Unit, Order] = {}
    for unit in state.units:
        roll = draw(st.integers(0, 9))
        if roll < 3:
            primitive[unit] = Hold(unit.kind, unit.location)
            continue
        if (
            roll == 3
            and unit.kind is UnitKind.ARMY
            and GRAPH.terrain(unit.location.province) is Terrain.COASTAL
        ):
            target = COASTAL_PROVINCES[draw(st.integers(0, len(COASTAL_PROVINCES) - 1))]
            if target != unit.location.province:
                primitive[unit] = Move(unit.kind, unit.location, Location(target), via_convoy=True)
                continue
        options = _destinations(GRAPH, unit)
        destination = options[draw(st.integers(0, len(options) - 1))]
        primitive[unit] = Move(unit.kind, unit.location, destination)

    orders: dict[Unit, Order] = dict(primitive)
    for unit in state.units:
        if draw(st.integers(0, 3)) != 0:
            continue
        if unit.kind is UnitKind.FLEET and GRAPH.terrain(unit.location.province) is Terrain.SEA:
            cargos = [
                order
                for order in primitive.values()
                if isinstance(order, Move) and order.via_convoy
            ]
            if cargos:
                cargo = cargos[draw(st.integers(0, len(cargos) - 1))]
                orders[unit] = Convoy(unit.kind, unit.location, cargo)
            continue
        subjects: list[Support] = []
        for other, order in primitive.items():
            if other == unit:
                continue
            if isinstance(order, Move):
                if _can_support_into(GRAPH, unit, order.destination.province):
                    subjects.append(
                        Support(
                            unit.kind,
                            unit.location,
                            Move(other.kind, other.location, order.destination),
                        )
                    )
            elif _can_support_into(GRAPH, unit, other.location.province):
                subjects.append(Support(unit.kind, unit.location, Hold(other.kind, other.location)))
        if subjects:
            orders[unit] = subjects[draw(st.integers(0, len(subjects) - 1))]

    sheets: dict[str, list[Order]] = {}
    for unit in state.units:  # canonical unit order within each power's sheet
        sheets.setdefault(unit.power, []).append(orders[unit])
    return sheets


@st.composite
def convoy_rich_sheets_for(draw: st.DrawFn, state: State) -> dict[str, list[Order]]:
    """Draw sheets dense in convoy structure over the given (reachable) position.

    Coastal armies attempt convoyed moves along *real* potential chains;
    sea fleets mostly convoy them, or attack/support-attack the convoying
    seas (disruption pressure); remaining units support the convoyed moves'
    entry contests or the sea battles. Everything stays sampled, so plain
    moves, holds and the occasional invalid order still occur.
    """
    occupied_seas = frozenset(
        unit.location.province
        for unit in state.units
        if unit.kind is UnitKind.FLEET and GRAPH.terrain(unit.location.province) is Terrain.SEA
    )
    orders: dict[Unit, Order] = {}
    convoyed: list[Move] = []

    for unit in state.units:  # pass 1: convoy attempts by coastal armies
        if (
            unit.kind is UnitKind.ARMY
            and len(convoyed) < _MAX_CONVOY_ATTEMPTS
            and GRAPH.terrain(unit.location.province) is Terrain.COASTAL
            and draw(st.integers(0, 9)) < 7
        ):
            origin = unit.location.province
            reachable = [
                target
                for target in COASTAL_PROVINCES
                if target != origin and potential_chain(GRAPH, occupied_seas, origin, target)
            ]
            if reachable:
                target = reachable[draw(st.integers(0, len(reachable) - 1))]
                move = Move(unit.kind, unit.location, Location(target), via_convoy=True)
                orders[unit] = move
                convoyed.append(move)

    for unit in state.units:  # pass 2: fleets service or attack the convoys
        if unit in orders or unit.kind is not UnitKind.FLEET:
            continue
        in_sea = GRAPH.terrain(unit.location.province) is Terrain.SEA
        roll = draw(st.integers(0, 9))
        if in_sea and convoyed and roll < 6:
            cargo = convoyed[draw(st.integers(0, len(convoyed) - 1))]
            orders[unit] = Convoy(unit.kind, unit.location, cargo)
            continue
        sea_targets = [
            loc
            for loc in _destinations(GRAPH, unit)
            if loc.province in occupied_seas and loc.province != unit.location.province
        ]
        if sea_targets and roll < 8:
            destination = sea_targets[draw(st.integers(0, len(sea_targets) - 1))]
            orders[unit] = Move(unit.kind, unit.location, destination)

    sea_attacks = [
        order for order in orders.values() if isinstance(order, Move) and not order.via_convoy
    ]
    for unit in state.units:  # pass 3: supports for landings and sea battles
        if unit in orders:
            continue
        roll = draw(st.integers(0, 9))
        subjects: list[Support] = []
        for move in convoyed + sea_attacks:
            if move.location == unit.location:
                continue
            if _can_support_into(GRAPH, unit, move.destination.province):
                subjects.append(
                    Support(
                        unit.kind,
                        unit.location,
                        Move(UnitKind.ARMY, move.location, move.destination)
                        if move.via_convoy
                        else Move(UnitKind.FLEET, move.location, move.destination),
                    )
                )
        if subjects and roll < 6:
            orders[unit] = subjects[draw(st.integers(0, len(subjects) - 1))]
        elif roll < 8:
            options = _destinations(GRAPH, unit)
            destination = options[draw(st.integers(0, len(options) - 1))]
            orders[unit] = Move(unit.kind, unit.location, destination)
        else:
            orders[unit] = Hold(unit.kind, unit.location)

    sheets: dict[str, list[Order]] = {}
    for unit in state.units:
        sheets.setdefault(unit.power, []).append(orders.get(unit, Hold(unit.kind, unit.location)))
    return sheets


@st.composite
def position_and_sheets(draw: st.DrawFn) -> tuple[State, dict[str, list[Order]]]:
    """Draw a reachable standard position and a mostly-legal sheet over it."""
    state = start_state()
    for _ in range(draw(st.integers(0, 2))):
        sheets = draw(sheets_for(state))
        state = adjudicate(STANDARD, state, sheets, graph=GRAPH).new_state
    return state, draw(sheets_for(state))


@st.composite
def convoy_rich_position_and_sheets(draw: st.DrawFn) -> tuple[State, dict[str, list[Order]]]:
    """Draw a convoy-rich position and a convoy-rich sheet over it.

    Advancing the position through convoy-rich phases drifts fleets into the
    seas, which is what makes the chains dense enough to be worth sampling.
    """
    state = start_state()
    for _ in range(draw(st.integers(0, 2))):
        sheets = draw(convoy_rich_sheets_for(state))
        state = adjudicate(STANDARD, state, sheets, graph=GRAPH).new_state
    return state, draw(convoy_rich_sheets_for(state))


# -- Beleriand: Areas, strengths, Dislodge/Bar ---------------------------------


def beleriand_start_state() -> State:
    """Build the Beleriand map's opening position."""
    units = [
        Unit(power, *parse_unit_spec(spec))
        for power, specs in BELERIAND_GRAPH.starting_units.items()
        for spec in specs
    ]
    return State.of("beleriand", "S25M", units)


def _spec_strength(unit: Unit) -> int | None:
    return unit.strength if unit.strength != 1 else None


def _ref_for(unit: Unit) -> UnitRef:
    return UnitRef(unit.power, unit.kind, Location(unit.location.province), _spec_strength(unit))


@st.composite
def beleriand_sheets_for(draw: st.DrawFn, state: State) -> dict[str, list[Order]]:
    """Draw a mostly-legal Beleriand sheet, dense in Area traffic.

    Each unit rolls hold / move / Dislodge / Bar; a second pass converts some
    units into supporters of the sampled primitives (support-move,
    support-hold, support-dislodge, support-bar). Strength prefixes are
    written whenever the unit's base strength is not 1, and subject owners whenever
    the subject province is shared -- the sheet-binding path under test is the
    one real play would exercise. Illegal rolls (permission, terrain, wrong
    victims) are features: Phase 0 is part of the system under test.
    """
    graph = BELERIAND_GRAPH
    by_province: dict[str, list[Unit]] = {}
    for unit in state.units:
        by_province.setdefault(unit.location.province, []).append(unit)

    def foreign_in(province: str, power: str) -> list[Unit]:
        return [u for u in by_province.get(province, []) if u.power != power]

    primitive: dict[int, Order] = {}
    for slot, unit in enumerate(state.units):
        strength = _spec_strength(unit)
        origin = unit.location.province
        roll = draw(st.integers(0, 9))
        if unit.kind is UnitKind.ARMY:
            neighbors = sorted(graph.army_adjacency.get(origin, frozenset()))
        else:
            neighbors = sorted(
                {loc.province for loc in graph.fleet_adjacency.get(unit.location, frozenset())}
            )
        if roll <= 2 or not neighbors:
            primitive[slot] = Hold(unit.kind, unit.location, strength)
            continue
        if roll <= 6:
            destination = neighbors[draw(st.integers(0, len(neighbors) - 1))]
            primitive[slot] = Move(unit.kind, unit.location, Location(destination), False, strength)
            continue
        if roll <= 8:  # a Dislodge against some foreign unit in a reachable Area
            victims = [
                victim
                for province in neighbors
                if graph.capacity(province) != 1
                for victim in foreign_in(province, unit.power)
            ]
            if victims:
                victim = victims[draw(st.integers(0, len(victims) - 1))]
                victim_order: Order | None = None
                # Sometimes name the victim's action, to cut one specific
                # support: a support the victim could give of another unit's
                # hold, with its spec normalised to the province-level victim
                # reference. Both engines share the victim-selection step
                # (docs/adjudication.tex Sec. 3.4), so this walks it on random
                # boards.
                if draw(st.integers(0, 2)) == 0:
                    reach = [
                        other
                        for other in state.units
                        if other.location.province != victim.location.province
                        and _can_support_into(graph, victim, other.location.province)
                    ]
                    if reach:
                        subj = reach[draw(st.integers(0, len(reach) - 1))]
                        crowded = len(by_province.get(subj.location.province, [])) > 1
                        victim_order = Support(
                            victim.kind,
                            Location(victim.location.province),
                            Hold(subj.kind, subj.location, _spec_strength(subj)),
                            _spec_strength(victim),
                            subj.power if crowded else None,
                        )
                primitive[slot] = Dislodge(
                    unit.kind, unit.location, _ref_for(victim), victim_order, strength
                )
                continue
        if graph.capacity(origin) != 1:  # a Bar against a foreign unit that could enter
            entrants = [
                entrant
                for province in sorted(graph.army_adjacency.get(origin, frozenset()))
                for entrant in foreign_in(province, unit.power)
            ]
            if entrants:
                entrant = entrants[draw(st.integers(0, len(entrants) - 1))]
                primitive[slot] = Bar(
                    unit.kind, unit.location, _ref_for(entrant), Location(origin), strength
                )
                continue
        primitive[slot] = Hold(unit.kind, unit.location, strength)

    orders: dict[int, Order] = dict(primitive)
    units = list(state.units)
    for slot, unit in enumerate(units):
        if draw(st.integers(0, 3)) != 0:
            continue
        subjects: list[Support] = []
        for other_slot, order in primitive.items():
            other = units[other_slot]
            if other_slot == slot:
                continue
            crowded = len(by_province.get(other.location.province, [])) > 1
            owner = other.power if crowded else None
            target: str | None = None
            subject: Hold | Move | Dislodge | Bar | None = None
            if isinstance(order, Move):
                target = order.destination.province
                subject = Move(
                    other.kind, other.location, order.destination, False, _spec_strength(other)
                )
            elif isinstance(order, Dislodge):
                target = order.victim.location.province
                # Half the tailed rolls support the generic form instead,
                # which is the only shape the enumeration offers: matching is
                # by victim reference alone, so a generic subject has to bind
                # an actual order that carries a victim-order tail.
                if order.victim_order is not None and draw(st.integers(0, 1)) == 0:
                    subject = replace(order, victim_order=None)
                else:
                    subject = order
            elif isinstance(order, Bar):
                target = order.destination.province
                subject = order
            elif isinstance(order, Hold):
                target = other.location.province
                subject = Hold(other.kind, other.location, _spec_strength(other))
            if subject is None or target is None:
                continue
            own = unit.location.province
            if unit.kind is UnitKind.ARMY:
                reachable = graph.army_reachable(own, target)
            else:
                reachable = bool(graph.fleet_destinations(unit.location, target))
            # A unit inside an Area also backs what is aimed at that Area, so
            # the draw has to reach the two shapes whose target is the
            # supporter's own province -- the Move entering it and the
            # Dislodge against a unit standing in it.
            if reachable or (target == own and graph.capacity(own) != 1):
                subjects.append(
                    Support(unit.kind, unit.location, subject, _spec_strength(unit), owner)
                )
        if subjects:
            orders[slot] = subjects[draw(st.integers(0, len(subjects) - 1))]

    sheets: dict[str, list[Order]] = {}
    for slot, unit in enumerate(units):  # canonical unit order within each power's sheet
        sheets.setdefault(unit.power, []).append(orders[slot])
    return sheets


@st.composite
def beleriand_position_and_sheets(draw: st.DrawFn) -> tuple[State, dict[str, list[Order]]]:
    """Draw a reachable Beleriand position and a sheet over it.

    The position is the rulebook start advanced by k random movement phases,
    so it is one play could actually produce.
    """
    state = beleriand_start_state()
    for _ in range(draw(st.integers(0, 2))):
        sheets = draw(beleriand_sheets_for(state))
        state = adjudicate(BELERIAND, state, sheets, graph=BELERIAND_GRAPH).new_state
    return state, draw(beleriand_sheets_for(state))


# -- the two-beach map: convoys onto a mixed coast ------------------------------

_TWO_BEACH_COASTS = ("LND", "ORI")
_TWO_BEACH_POWERS = ("BLU", "RED")


@st.composite
def two_beach_position_and_sheets(draw: st.DrawFn) -> tuple[State, dict[str, list[Order]]]:
    """Draw a two-beach position dense in convoys, and a Beleriand sheet over it.

    The board is sampled directly rather than played forward: the map has no
    land edge and no opening, and the positions wanted are the ones a shipped
    map cannot hold -- crossings onto a coast with one marked and one free sea,
    under fleets of either base strength that convoy, idle off every chain, attack the
    convoying seas or support into them, and coastal fleets whose support a
    landing army cuts. Those are the inputs of the ordered-chain toll and of
    the convoy paradoxes it feeds a strength into.
    """
    graph = TWO_BEACH
    units: list[Unit] = []
    for province in sorted(graph.provinces):
        coastal = graph.terrain(province) is Terrain.COASTAL
        if draw(st.integers(0, 9)) >= (9 if coastal else 8):
            continue
        army = coastal and draw(st.integers(0, 9)) < 7
        units.append(
            Unit(
                _TWO_BEACH_POWERS[draw(st.integers(0, 1))],
                UnitKind.ARMY if army else UnitKind.FLEET,
                Location(province),
                1 if draw(st.integers(0, 4)) < 2 else 2,
            )
        )
    state = State.of(graph.name, "S25M", units)

    def neighbors(unit: Unit) -> list[str]:
        return sorted(loc.province for loc in graph.fleet_adjacency.get(unit.location, frozenset()))

    primitive: dict[int, Order] = {}
    crossings: list[Move] = []
    for slot, unit in enumerate(units):
        strength = _spec_strength(unit)
        roll = draw(st.integers(0, 9))
        if unit.kind is UnitKind.ARMY:
            if roll < 8:
                origin = unit.location.province
                target = next(coast for coast in _TWO_BEACH_COASTS if coast != origin)
                move = Move(unit.kind, unit.location, Location(target), True, strength)
                primitive[slot] = move
                crossings.append(move)
            else:
                primitive[slot] = Hold(unit.kind, unit.location, strength)
        elif roll < 4:
            primitive[slot] = Hold(unit.kind, unit.location, strength)
        else:
            options = neighbors(unit)
            target = options[draw(st.integers(0, len(options) - 1))]
            primitive[slot] = Move(unit.kind, unit.location, Location(target), False, strength)

    orders: dict[int, Order] = dict(primitive)
    for slot, unit in enumerate(units):
        if unit.kind is not UnitKind.FLEET:
            continue
        roll = draw(st.integers(0, 9))
        at_sea = graph.terrain(unit.location.province) is Terrain.SEA
        if at_sea and crossings and roll < 7:
            cargo = crossings[draw(st.integers(0, len(crossings) - 1))]
            orders[slot] = Convoy(unit.kind, unit.location, cargo, _spec_strength(unit))
            continue
        if roll >= 8:
            continue  # keeps its primitive: a hold, or an attack on a neighbouring sea
        reach = set(neighbors(unit))
        subjects: list[Support] = []
        for other_slot, order in primitive.items():
            if other_slot == slot:
                continue
            other = units[other_slot]
            subject: Hold | Move
            if isinstance(order, Move):
                target = order.destination.province
                subject = Move(
                    other.kind, other.location, order.destination, False, _spec_strength(other)
                )
            else:
                target = other.location.province
                subject = Hold(other.kind, other.location, _spec_strength(other))
            if target in reach:
                subjects.append(
                    Support(unit.kind, unit.location, subject, _spec_strength(unit), None)
                )
        if subjects:
            orders[slot] = subjects[draw(st.integers(0, len(subjects) - 1))]

    sheets: dict[str, list[Order]] = {}
    for slot, unit in enumerate(units):
        sheets.setdefault(unit.power, []).append(orders[slot])
    return state, sheets
